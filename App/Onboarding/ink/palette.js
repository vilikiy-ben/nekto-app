// Цвета иллюстраций — из палитры приложения (`App/Sources/Design/Theme.swift`).
//
// ink   — «синька» Ink.accent: вся линия рисунка.
// tint  — бледная синька, второй прогон как в ризографии: пятна сдвинуты от контура на пару пикселей.
// mark  — очки, вымаранные плашки, ключ: всё, что скрыто. Единственное, что нарисовано не синим.
//         На светлом — графит, как очки на иконке. На тёмном — тёплый белый: синие очки, как на тёмной
//         иконке, сливались бы с синей линией рисунка.
// paper — бумага панели под рисунком; ею «стирают» то, что стоит позади.
// sheet — светлее бумаги: листы и предметы, которые лежат поверх панели.
// mass  — тяжёлые массы сцен (плита сканера, корпус Mac, стенка папки). На светлом — графит, на тёмном —
//         тёмный графит чуть светлее бумаги: белые плиты в тёмной теме теряли тяжесть. Светлый hex на единицу
//         отличается от mark, чтобы в неподвижном кадре SVG роли различались по цвету.

