"""Поиск ФИО по совокупности свидетельств: словарь, регистр, соседи, слова документа, модель.

Модель здесь подменена: каждому тесту явно сказано, что она «ответила». Так видно, какое свидетельство решает.
Имена и фразы вымышленные; каждая показывает одно явление, на котором ошибается модель или словарь.
"""
import re

import pytest

from nekto_engine.model import Tag
from nekto_engine.names import finder


def tags(text: str, said: dict[str, tuple[str, float]] | None = None) -> list[Tag]:
    """Ответ модели: {слово: (метка, уверенность)} → метки на всех вхождениях слова."""
    out = []
    for word, (label, score) in (said or {}).items():
        out += [Tag(m.start(), m.end(), label, score) for m in re.finditer(rf"(?<!\w){re.escape(word)}(?!\w)", text)]
    return sorted(out, key=lambda t: t.start)


def found(text: str, said=None, document: list[str] | None = None) -> list[str]:
    vocabulary = finder.Vocabulary(document if document is not None else [text])
    return [text[a:b] for a, b, _score in finder.find(text, tags(text, said), vocabulary)]


L, F = ("LAST_NAME", 0.99), ("FIRST_NAME", 0.99)


# ---------- модель уверена, но это не имя ----------

@pytest.mark.parametrize("text,said", [
    ("Без скриптов для продажников к звонкам не пускаем.", {"продажников": L}),                 # жаргон строчными
    ("Говорят, продажник уже в отпуске.", {"продажник": L}),
    ("Таблицу кэшбэков обновим к пятнице.", {"кэшбэков": L}),
    ("Новый принтер — топчик, печатает сам.", {"топчик": F}),
    ("Благодарю за оперетивность склада.", {"оперетивность": L}),                          # опечатка
    ("Акт подписали в ЦФО и ОТК за день.", {"ЦФО": L, "ОТК": L}),                          # аббревиатуры
    ("На складе все просто ГЕРОИ!", {"ГЕРОИ": F}),
    ("Кладовщики — герои недели. Всё в срок.", {"Кладовщики": ("LAST_NAME", 0.8)}),   # обычное слово в начале фразы
    ("Документы сдала в бухгалтерию к понедельнику.", {"к": L}),                          # одна буква
    ("Заказ из каталога МаРТа пришёл вчера.", {}),                                          # регистр вперемешку: не «Марта»
    ("Вопросы — в ИИ-ассистентов чат.", {}),                                                   # «-ов» в слове через дефис
])
def test_model_alone_is_not_enough(text, said):
    assert found(text, said) == []


def test_word_the_document_writes_in_lowercase_is_not_a_surname():
    """«Продажник» в начале предложения с заглавной — то же слово, что «продажник», «продажника», «продажников» по всему документу."""
    document = ["Счёт выставляет продажник.", "Продажник созвонится с клиентом.", "Спросите у продажника.", "Продажников не хватает."]
    for line in document:
        assert found(line, {"Продажник": L, "Продажников": L}, document) == []
    # а без такого документа «Рихтер сказал» с голосом модели — человек
    assert found("Рихтер обещал заехать.", {"Рихтер": L}) == ["Рихтер"]


