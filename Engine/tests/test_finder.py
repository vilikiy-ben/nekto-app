def test_lowercase_name_known_to_the_document():
    doc = ["18:48 Таня: жду цифры от Вики. она обещала до 6", "18:49 Лёха: вика ушла уже, я видел"]
    assert found(doc[1], {}, doc) == ["Лёха", "вика"]
    assert found("18:49 Лёха: вика ушла уже, я видел", {}) == ["Лёха"]          # без «Вики» в документе — слово


def test_address_in_email_does_not_make_surname_a_word():
    doc = ["Surname / Фамилия", "GINIYATULLINA / Гиниятуллина", "e-mail: giniyatullina@example.org"]
    assert found(doc[1], {"GINIYATULLINA": L, "Гиниятуллина": L}, doc) == ["GINIYATULLINA", "Гиниятуллина"]


