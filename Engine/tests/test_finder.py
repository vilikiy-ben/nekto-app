def test_homonym_followed_by_a_preposition_is_a_noun_even_if_the_model_insists():
    said = {"Надежда": F, "Роман": F, "Вера": F}
    assert found("ТЗ переписывали пять раз. Надежда только на то, что успеем.", said) == []
    assert found("— Роман с агентством заканчиваем в июне.", said) == []
    assert found("Вера сказала, что придёт. Роман, привет!", said) == ["Вера", "Роман"]


def test_line_after_a_number_is_not_a_code():
    """Строка кончается цифрой, следующая начинается с фамилии: это не «Бикбаев-2»."""
    assert found("Белый П. А. 01.01.60 89161000000\nСоловей К. Д. 02.02.61 89161007919") == ["Белый П. А.", "Соловей К. Д."]
    assert found("Версия Бикбаев-2 выпущена, модуль Орлов_3 тоже.") == []


def test_two_people_without_a_comma_are_split_by_roles():
    text = "Благодарим: Орлов Иван Петрович Зуева Мария Сергеевна"
    said = {w: L for w in ("Орлов", "Зуева")}
    assert found(text, said) == ["Орлов Иван Петрович", "Зуева Мария Сергеевна"]


def test_gate_skips_text_without_candidates():
    assert not finder.needs_model("Все отлично, спасибо большое за работу!")
    assert not finder.needs_model("Пункт выдачи / Возвраты")
    assert not finder.needs_model("ТЗ и КП согласуем через CRM, сроки по SLA.")
    assert finder.needs_model("Спасибо Ире за помощь.")
    assert finder.needs_model("В целом всё хорошо, но оксана иногда не отвечает.")
    assert finder.needs_model("Рихтер обещал заехать.")            # слово вне словаря в начале фразы
    assert finder.needs_model("Обсудили с Выдрой сроки.")             # заглавная в середине фразы


